import json, sys
meta = json.load(open(sys.argv[1], encoding="utf-8"))
ws = set(meta["workspace_members"])
allowed = {"MIT","Apache-2.0","BSD-2-Clause","BSD-3-Clause","ISC","Zlib","Unicode-3.0","Unlicense","MPL-2.0"}
# Only third-party packages in the lock file (exclude workspace members and path deps)
rows = []
ffi = []
for p in meta["packages"]:
    src = p.get("source")
    name, ver = p["name"], p["version"]
    kinds = set(k for t in p["targets"] for k in t["kind"])
    build = "custom-build" in kinds
    if p["id"] in ws:
        continue
    lic = p.get("license")
    srcs = "crates.io" if src and "registry" in src else ("git" if src and src.startswith("git+") else "other")
    if name.endswith("-sys") or p.get("links") or build:
        ffi.append((name, ver, "links=%s" % p.get("links"), "build.rs" if build else ""))
    rows.append((name, ver, lic, p.get("license_file"), srcs))
# license expressions: flag as problem if none of the alternatives is allowed (OR) or any AND term not allowed
import re
def ok(expr):
    if not expr: return False
    norm = expr.replace("(", "").replace(")", "").replace("/", " OR ")
    alts = [a.strip() for a in re.split(r"\s+OR\s+", norm)]
    # ok if any OR alternative is fully allowed (AND terms all allowed)
    for a in alts:
        terms = [t.strip() for t in re.split(r"\s+AND\s+", a)]
        if all(t in allowed or t.replace("WITH","").strip() in allowed for t in terms):
            return True
    return False
out = []
flag = []
for name, ver, lic, lf, srcs in sorted(rows, key=lambda r: (r[0].lower(), r[1])):
    status = ""
    if not lic:
        status = "NO LICENCE FIELD" + (" (license_file=%s)" % lf if lf else "")
    elif not ok(lic):
        status = "REVIEW"
    elif lic.strip() in ("Apache-2.0", "Apache-2.0 WITH LLVM-exception"):
        status = "APACHE-ONLY: on the requested allow list, but deny.toml rejects Apache-2.0-only crates"
    if status: flag.append((name, ver, lic, status))
    out.append((name, ver, lic or "(none)", srcs, status))
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write("# Third-party notices\n\n")
    f.write("Generated by a script reading `cargo metadata --format-version 1` (the `license` field of each package in `Cargo.lock`). Workspace members are excluded.\n\n")
    f.write("To regenerate:\n\n```sh\ncargo metadata --format-version 1 > meta.json\npython scripts/gen_third_party.py meta.json THIRD_PARTY.md\n```\n\n")
    f.write("Note: the `license` field is the SPDX expression the crate declares. It has not been checked against the licence text. Packages marked REVIEW use an expression with no alternative fully on the allow list (MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, Zlib, Unicode-3.0, Unlicense, MPL-2.0). MPL-2.0 is listed on the allow list here only so that it is reported; it is not silently accepted.\n\n")
    f.write("## Flagged packages\n\n")
    if flag:
        f.write("| Package | Version | Licence | Flag |\n|---|---|---|---|\n")
        for n,v,l,s in flag: f.write(f"| {n} | {v} | {l or '(none)'} | {s} |\n")
    else:
        f.write("None.\n")
    f.write("\n## All third-party packages\n\n| Package | Version | Licence | Source |\n|---|---|---|---|\n")
    for n,v,l,s,st in out: f.write(f"| {n} | {v} | {l} | {s} |\n")
print("packages:", len(out))
print("flagged:", flag)
print("ffi-candidates:", ffi)
